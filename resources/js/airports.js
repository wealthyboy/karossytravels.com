export const searchAirports = (query, limit = 7) => {
    const term = query.trim().toLocaleLowerCase();
    if (!term) return [];

    return majorAirports
        .map((airport) => {
            const code = airport.code.toLowerCase();
            const city = airport.city.toLowerCase();
            const country = airport.country.toLowerCase();
            const name = airport.name.toLowerCase();
            let score = 99;
            if (code === term) score = 0;
            else if (city === term) score = 1;
            else if (code.startsWith(term)) score = 2;
            else if (city.startsWith(term)) score = 3;
            else if (country.startsWith(term)) score = 4;
            else if (`${city} ${name} ${country} ${code}`.includes(term)) score = 5;
            return { airport, score };
        })
        .filter(({ score }) => score < 99)
        .sort((a, b) => a.score - b.score || a.airport.city.localeCompare(b.airport.city))
        .slice(0, limit)
        .map(({ airport }) => airport);
};
